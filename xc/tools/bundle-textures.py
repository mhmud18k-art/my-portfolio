"""Rebuilds textures/textures.js from the .webp files in textures/.

WebGL won't take image files on a page opened straight from disk (file://), so the world
reads its textures from this script as data URLs instead. Run it from the xc folder after
changing a texture:  python tools/bundle-textures.py
"""
import base64
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent / 'textures'
entries = []
for f in sorted(root.glob('*.webp')):
    data = base64.b64encode(f.read_bytes()).decode('ascii')
    entries.append(f'  "{f.stem}": "data:image/webp;base64,{data}"')
(root / 'textures.js').write_text(
    '// generated by tools/bundle-textures.py from textures/*.webp; do not edit by hand\n'
    'window.TEXTURES = {\n' + ',\n'.join(entries) + '\n};\n')
print('wrote', root / 'textures.js')
