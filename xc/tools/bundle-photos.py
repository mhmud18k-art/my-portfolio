"""Rebuilds photos/photos.js from photos/1.jpg ... photos/5.jpg.

WebGL won't take image files on a page opened straight from disk (file://), so the
3D hero reads the photos from this script as data URLs instead. Run it from the xc
folder after replacing a photo:  python tools/bundle-photos.py
"""
import base64
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent / 'photos'
urls = []
for k in range(1, 6):
    data = (root / f'{k}.jpg').read_bytes()
    urls.append('data:image/jpeg;base64,' + base64.b64encode(data).decode('ascii'))
body = ',\n'.join(f'  "{u}"' for u in urls)
(root / 'photos.js').write_text(
    '// generated by tools/bundle-photos.py from photos/1.jpg ... 5.jpg; do not edit by hand\n'
    f'window.PHOTOS = [\n{body}\n];\n')
print('wrote', root / 'photos.js')
